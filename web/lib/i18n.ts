export const TEXTS = { ru, kk };
export type Texts = typeof ru;

const KEY = "seriq_lang";

/** Язык интерфейса: по умолчанию казахский, выбор запоминается на этом устройстве. */
export function useLang(): [Lang, (l: Lang) => void, Texts] {
  const [lang, setLangState] = useState<Lang>("kk");
  useEffect(() => {
    try {
      const saved = localStorage.getItem(KEY);
      if (saved === "kk" || saved === "ru") setLangState(saved);
    } catch {
      /* хранилище недоступно — остаёмся на языке по умолчанию */
    }
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(KEY, l);
    } catch {
      /* ничего страшного */
    }
  };
  return [lang, setLang, TEXTS[lang]];
}
